export function translate(locale: AppLocale, kazakh: string, english: string, russian?: string) {
  if (locale === 'kk') return kazakh;
  if (locale === 'ru') return russian || RUSSIAN_TRANSLATIONS[english] || english;
  return english;
}

export function dateLocale(locale: AppLocale) {
  if (locale === 'kk') return 'kk-KZ';
  return locale === 'ru' ? 'ru-RU' : 'en-US';
}
